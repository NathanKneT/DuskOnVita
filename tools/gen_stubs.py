#!/usr/bin/env python3
"""Generate named trap stubs for every symbol a probe link left undefined.

The probe ELF is the real game graph (Vita main + Dusklight game libraries)
linked with --unresolved-symbols=ignore-all and relocations kept (-Wl,-q, set by
the VitaSDK toolchain). Every strong undefined symbol becomes either
  * a function that calls twv_stub_trap("<symbol>") (platform/vita/runtime/stub_trap.cpp), or
  * a zero-filled data object, when nothing calls it and its name is not a function,
so the final link resolves completely while every missing piece stays visible:
reaching a stub stops the process with the symbol name in runtime.jsonl.
The report groups the stubs by owner; that list is the porting backlog.
"""
import argparse
import collections
import re
import subprocess
import sys

CALL_RELOCS = {"R_ARM_THM_CALL", "R_ARM_THM_JUMP24", "R_ARM_THM_JUMP19", "R_ARM_CALL", "R_ARM_JUMP24", "R_ARM_PC24"}
DATA_SIZE = 256  # bytes reserved per unknown data symbol (size is not recoverable from a reference)


def run(cmd, stdin=None):
    return subprocess.run(cmd, input=stdin, capture_output=True, text=True, check=True).stdout


def undefined_symbols(nm, elf):
    syms = set()
    for line in run([nm, "--no-demangle", "-u", elf]).splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[0] == "U":  # 'w' (weak undefined) stays 0 by design
            syms.add(parts[1])
    return syms


def reloc_types(readelf, elf, wanted):
    """Map symbol -> set of relocation types referencing it (from the kept .rel sections)."""
    types = collections.defaultdict(set)
    proc = subprocess.Popen([readelf, "-rW", elf], stdout=subprocess.PIPE, text=True)
    for line in proc.stdout:
        parts = line.split()
        # Offset Info Type Sym.Value Sym.Name
        if len(parts) >= 5 and parts[2].startswith("R_ARM_") and parts[4] in wanted:
            types[parts[4]].add(parts[2])
    proc.wait()
    return types


def demangle(cxxfilt, names):
    out = run([cxxfilt], stdin="\n".join(names) + "\n").splitlines()
    return dict(zip(names, out))


def owner(sym, pretty):
    """Coarse grouping for the report: which layer is expected to provide it."""
    p = pretty
    if re.match(r"^(GX|GD|VI|PAD|SI|OS|DVD|CARD|AI|AR|ARQ|DSP|AX|THP|MTX|PSMTX|PSVEC|C_MTX|C_VEC|EXI|DB|LC)[A-Z_]", p):
        return "aurora (Dolphin SDK API)"
    if p.startswith("aurora") or p.startswith("aurora::") or sym.startswith("aurora_"):
        return "aurora (core/gfx)"
    if p.startswith("SDL_") or sym.startswith("SDL_"):
        return "SDL3"
    if p.startswith("borealis::"):
        return "borealis"
    if p.startswith("dusk::") or p.startswith("Dusk") or "dusk" in p.split("(")[0].lower():
        return "dusklight (src/dusk)"
    if p.startswith("ImGui") or p.startswith("Rml"):
        return "ui (imgui/rmlui)"
    if p.startswith("std::") or p.startswith("__"):
        return "c++ runtime"
    return "other"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--elf", required=True)
    ap.add_argument("--nm", required=True)
    ap.add_argument("--readelf", required=True)
    ap.add_argument("--cxxfilt", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--report", required=True)
    a = ap.parse_args()

    syms = sorted(undefined_symbols(a.nm, a.elf))
    relocs = reloc_types(a.readelf, a.elf, set(syms))
    pretty = demangle(a.cxxfilt, syms) if syms else {}

    # Our own code is never stubbed: an unresolved twv symbol is a link-order or
    # build-list mistake, and stubbing it would hide a missing implementation.
    ours = [s for s in syms if pretty.get(s, s).startswith(("twv::", "twv_")) and s != "twv_stub_trap"]
    if ours:
        for s in ours:
            print(f"gen_stubs: error: own symbol unresolved: {pretty.get(s, s)}", file=sys.stderr)
        return 1

    funcs, data = [], []
    for s in syms:
        p = pretty.get(s, s)
        is_mangled = s.startswith("_Z")
        called = bool(relocs.get(s, set()) & CALL_RELOCS)
        vtable_or_rtti = s.startswith(("_ZTV", "_ZTI", "_ZTS", "_ZTT", "_ZGV"))
        if vtable_or_rtti:
            data.append(s)
        elif called or (is_mangled and "(" in p):
            funcs.append(s)
        else:
            data.append(s)

    with open(a.out, "w") as f:
        f.write("/* Generated by tools/gen_stubs.py from the probe link. Do not edit. */\n")
        f.write("extern void twv_stub_trap(const char*) __attribute__((noreturn));\n\n")
        for i, s in enumerate(funcs):
            f.write(f'void twv_fn_{i}(void) __asm__("{s}");\n')
            f.write(f'void twv_fn_{i}(void) {{ twv_stub_trap("{s}"); }}\n')
        f.write("\n")
        for i, s in enumerate(data):
            f.write(f'__attribute__((aligned(16))) unsigned char twv_data_{i}[{DATA_SIZE}] __asm__("{s}");\n')

    groups = collections.defaultdict(list)
    for s in syms:
        groups[owner(s, pretty.get(s, s))].append(s)
    with open(a.report, "w") as r:
        r.write(f"undefined symbols stubbed: {len(syms)} ({len(funcs)} functions, {len(data)} data)\n\n")
        for g in sorted(groups, key=lambda k: -len(groups[k])):
            r.write(f"{g}: {len(groups[g])}\n")
        for g in sorted(groups, key=lambda k: -len(groups[k])):
            r.write(f"\n## {g} ({len(groups[g])})\n")
            for s in groups[g]:
                kind = "data" if s in data else "func"
                r.write(f"{kind} {pretty.get(s, s)}\n")
    print(f"gen_stubs: {len(syms)} undefined -> {len(funcs)} function stubs, {len(data)} data stubs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
